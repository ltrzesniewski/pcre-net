    public static IReadOnlyList<Pcre2Constant> Items { get; private set; } = [];

    public static void ReadFrom(string headerPath)
        => Items = [.. Parse(headerPath)];

    private static IEnumerable<Pcre2Constant> Parse(string headerPath)
    {
        var commentRe = new Regex(
            @"/\* .*? \*/",
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        var defineRe = new Regex(
            """
            ^ \s* \# \s* define \s+
            (?<name>PCRE2_\w+) \s+
            \(? \s*
                (?<value> -? (?:0x)? [0-9]+ )
                [uU]?
            \s* \)?
            \s* $
            """,
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace | RegexOptions.Multiline
        );

        foreach (var rawLine in File.ReadLines(headerPath))
        {
            if (rawLine.Contains("Obsolete", StringComparison.OrdinalIgnoreCase))
                continue;

            var line = commentRe.Replace(rawLine, string.Empty);
            var match = defineRe.Match(line);

            if (!match.Success)
                continue;

            var (name, value) = (match.Groups["name"].Value, match.Groups["value"].Value);

            if (name is "PCRE2_MAJOR" or "PCRE2_MINOR" or "PCRE2_LOCAL_WIDTH")
                continue;

            yield return new Pcre2Constant(name, value);
        }
    }

    public static string ToMemberName(string constantName)
    {
        if (!constantName.StartsWith("PCRE2_", StringComparison.Ordinal))
            throw new ArgumentException($"Invalid constant name: '{constantName}'", nameof(constantName));

        var memberName = constantName;

        foreach (var cut in _cutPositions)
        {
            if (constantName == cut.Replace("|", string.Empty))
            {
                memberName = cut.Replace("|", "_");
                break;
            }
        }

        memberName = Regex.Replace(
            memberName,
            """
            ^PCRE2_
            (?:
                (?: EXTRA | ERROR | INFO | CONFIG ) _
            )?
            """,
            string.Empty,
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        memberName = Regex.Replace(
            memberName.ToLowerInvariant(),
            @"(?:^|_)(?<char>\w)",
            m => m.Groups["char"].Value.ToUpperInvariant()
        );

        return memberName;
    }

    private static string? ToMemberClass(string constantName)
    {
        if (Items.All(i => i.Name != constantName))
            return null;

        if (constantName.StartsWith("PCRE2_EXTRA_", StringComparison.Ordinal))
            return "PcreExtraCompileOptions";

        if (constantName.StartsWith("PCRE2_ERROR_", StringComparison.Ordinal))
            return "PcreErrorCode";

        if (constantName.StartsWith("PCRE2_INFO_", StringComparison.Ordinal))
            return "PcrePatternInfo";

        if (constantName.StartsWith("PCRE2_CONFIG_", StringComparison.Ordinal))
            return "PcreBuildInfo";

        return "PcreOptions";
    }

    public static string ToXmlDocSeeCref(string constantName)
    {
        if (ToMemberClass(constantName) is { } memberClass)
            return $"""<see cref="{memberClass}.{ToMemberName(constantName)}"/>""";

        return $"<c>{constantName}</c>";
    }

