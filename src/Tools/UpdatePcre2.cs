#!/usr/bin/env dotnet

// To update PCRE2:
// - Delete the contents of the PCRE directory
// - Extract the PCRE2 release into the PCRE directory
// - Run this script: dotnet UpdatePcre2.cs

#:include UpdatePcre2.Data.cs
#:include ../PCRE.NET.Analyzers/Analyzers/CodeWriter.cs

using System.Text.RegularExpressions;
using PCRE.Analyzers;

var rootPath = GetRepositoryRootPath();
var pcre2SrcDir = Path.Combine(rootPath, "src", "PCRE", "src");
string pcre2Version;

Console.WriteLine();
Console.WriteLine($"Updating PCRE2 in repository: {rootPath}");

// Patch PCRE2
{
    File.Copy(
        Path.Combine(pcre2SrcDir, "pcre2.h.generic"),
        Path.Combine(pcre2SrcDir, "pcre2.h"),
        overwrite: true
    );

    File.Copy(
        Path.Combine(pcre2SrcDir, "pcre2_chartables.c.dist"),
        Path.Combine(pcre2SrcDir, "pcre2_chartables.c"),
        overwrite: true
    );

    var configFile = File.ReadAllText(Path.Combine(pcre2SrcDir, "config.h.generic"));

    File.WriteAllText(
        Path.Combine(pcre2SrcDir, "config.h"),
        // language=cpp
        $"""

         #include "../../PCRE.NET.Native/pcre2config.h"

         {configFile}
         """.ReplaceLineEndings("\n")
    );

    pcre2Version = Regex.Match(
        configFile,
        """
        ^\s*#define\s+PACKAGE_VERSION\s+"(?<version>[\w.-]+)"
        """,
        RegexOptions.CultureInvariant | RegexOptions.Multiline
    ).Groups["version"].Value;

    Console.WriteLine(" ✅ PCRE2 patched");
}

var constants = PcreConstant.ParsePcre2Header(Path.Combine(pcre2SrcDir, "pcre2.h")).ToArray();
var writer = new CodeWriter();

// Update PcreConstants.cs
{
    writer.Clear().AppendLine(
        """
        //------------------------------------------------------------------------------
        // <auto-generated>
        //     This code was generated by UpdatePcre2.cs - do not update manually.
        // </auto-generated>
        //------------------------------------------------------------------------------

        #nullable enable

        namespace PCRE.Internal;

        """
    );

    using (writer.WriteBlock("internal static class PcreConstants"))
    {
        foreach (var (type, name, value) in constants)
            writer.AppendLine($"public const {type} {name} = {value};");
    }

    File.WriteAllText(
        Path.Combine(rootPath, "src", "PCRE.NET", "Internal", "PcreConstants.cs"),
        writer.ToString()
    );

    Console.WriteLine(" ✅ PcreConstants.cs updated");
}

// Update PcreErrorCode.cs
{
    var errorCodeFilePath = Path.Combine(rootPath, "src", "PCRE.NET", "PcreErrorCode.cs");
    var fileContents = File.ReadAllText(errorCodeFilePath);
    var match = Regex.Match(
        fileContents,
        """
        ^[ ]*\#region[ ]+Generated\r?\n
        (?<generated>.*?)
        ^[ ]*\#endregion\r?\n
        """,
        RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace | RegexOptions.Singleline | RegexOptions.Multiline
    );

    if (!match.Success)
        throw new InvalidOperationException("Could not find the generated region in PcreErrorCode.cs.");

    var generatedGroup = match.Groups["generated"];
    writer.Clear().AppendLine(fileContents[..generatedGroup.Index]);

    using (writer.Indented())
    {
        var errorMessages = PcreErrorMessage.ParseErrorFile(Path.Combine(pcre2SrcDir, "pcre2_error.c"))
                                            .ToDictionary(i => i.Value);

        foreach (var constant in constants.Where(i => i.IsError))
        {
            var errorMessage = errorMessages[int.Parse(constant.Value)];

            writer.AppendLine("/// <summary>");
            writer.AppendLine($"/// <c>{constant.Name}</c> - {errorMessage.ToXmlDocComment()}");
            writer.AppendLine("/// </summary>");
            writer.AppendLine($"{constant.ToMemberName()} = PcreConstants.{constant.Name},");
            writer.AppendLine();
        }
    }

    writer.AppendLine().Append(fileContents[(generatedGroup.Index + generatedGroup.Length)..]);
    File.WriteAllText(errorCodeFilePath, writer.ToString());

    Console.WriteLine(" ✅ PcreErrorCode.cs updated");
}

Console.WriteLine();
Console.WriteLine($"PCRE2 successfully updated to version {pcre2Version}");
return;

static string GetRepositoryRootPath()
{
    for (var path = Environment.CurrentDirectory; path is not null; path = Path.GetDirectoryName(path))
    {
        if (Directory.Exists(Path.Combine(path, ".git")))
            return path;
    }

    throw new InvalidOperationException("Could not find the repository root path.");
}
