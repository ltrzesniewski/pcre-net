#!/usr/bin/env dotnet

// To update PCRE2:
// - Delete the contents of the PCRE directory
// - Extract the PCRE2 release into the PCRE directory
// - Run this script: dotnet UpdatePcre2.cs

#:include ../PCRE.NET.Analyzers/Analyzers/CodeWriter.cs

using System.Net;
using System.Text.RegularExpressions;
using PCRE.Analyzers;

var rootPath = GetRepositoryRootPath();
var pcre2SrcDir = Path.Combine(rootPath, "src", "PCRE", "src");
string pcre2Version;

Console.WriteLine();
Console.WriteLine($"Updating PCRE2 in repository: {rootPath}");

var constants = PcreConstant.Parse(
    Path.Combine(pcre2SrcDir, "pcre2.h.generic"),
    Path.Combine(rootPath, "src", "PCRE.NET", "PcreOptions.cs"),
    Path.Combine(rootPath, "src", "PCRE.NET", "PcreExtraCompileOptions.cs")
).ToArray();

var writer = new CodeWriter();

PatchPcre2();
UpdatePcreConstants();
UpdatePcreErrorCode();

Console.WriteLine();
Console.WriteLine($"PCRE2 successfully updated to version {pcre2Version}");
return;

static string GetRepositoryRootPath()
{
    for (var path = Environment.CurrentDirectory; path is not null; path = Path.GetDirectoryName(path))
    {
        if (Directory.Exists(Path.Combine(path, ".git")))
            return path;
    }

    throw new InvalidOperationException("Could not find the repository root path.");
}

void PatchPcre2()
{
    (string fileName, string[] includes)[] patches =
    [
        ("pcre2.h", ["pcre2.h.generic"]),
        ("pcre2_chartables.c", ["pcre2_chartables.c.dist"]),
        ("config.h", ["../../PCRE.NET.Native/pcre2config.h", "config.h.generic"])
    ];

    foreach (var (fileName, filesToInclude) in patches)
    {
        var identifier = $"PCRENET_{fileName.Replace('.', '_').ToUpperInvariant()}";
        var isHeaderFile = fileName.EndsWith(".h", StringComparison.Ordinal);

        writer.Clear()
              .AppendLine()
              .AppendLine("/* Generated with UpdatePcre2.cs */")
              .AppendLine();

        if (isHeaderFile)
        {
            writer.AppendLine($"#ifndef {identifier}")
                  .AppendLine($"#define {identifier}")
                  .AppendLine();
        }

        foreach (var fileToInclude in filesToInclude)
        {
            writer.AppendLine($"""
                #include "{fileToInclude}"
                """
            );
        }

        if (isHeaderFile)
        {
            writer.AppendLine()
                  .AppendLine($"#endif /* {identifier} */");
        }

        File.WriteAllText(
            Path.Combine(pcre2SrcDir, fileName),
            writer.ToString().ReplaceLineEndings("\n")
        );
    }

    var configFile = File.ReadAllText(Path.Combine(pcre2SrcDir, "config.h.generic"));

    pcre2Version = Regex.Match(
        configFile,
        """
        ^\s*#define\s+PACKAGE_VERSION\s+"(?<version>[\w.-]+)"
        """,
        RegexOptions.CultureInvariant | RegexOptions.Multiline
    ).Groups["version"].Value;

    Console.WriteLine(" ✅ PCRE2 patched");
}

void UpdatePcreConstants()
{
    writer.Clear().AppendLine(
        """
        //------------------------------------------------------------------------------
        // <auto-generated>
        //     This code was generated by UpdatePcre2.cs - do not update manually.
        // </auto-generated>
        //------------------------------------------------------------------------------

        #nullable enable

        namespace PCRE.Internal;

        """
    );

    using (writer.WriteBlock("internal static class PcreConstants"))
    {
        foreach (var (type, name, value, _) in constants)
            writer.AppendLine($"public const {type} {name} = {value};");
    }

    File.WriteAllText(
        Path.Combine(rootPath, "src", "PCRE.NET", "Internal", "PcreConstants.cs"),
        writer.ToString()
    );

    Console.WriteLine(" ✅ PcreConstants.cs updated");
}

void UpdatePcreErrorCode()
{
    var errorCodeFilePath = Path.Combine(rootPath, "src", "PCRE.NET", "PcreErrorCode.cs");
    var fileContents = File.ReadAllText(errorCodeFilePath);
    var match = Regex.Match(
        fileContents,
        """
        ^[ ]*\#region[ ]+Generated\r?\n
        (?<generated>.*?)
        ^[ ]*\#endregion\r?\n
        """,
        RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace | RegexOptions.Singleline | RegexOptions.Multiline
    );

    if (!match.Success)
        throw new InvalidOperationException("Could not find the generated region in PcreErrorCode.cs.");

    var generatedGroup = match.Groups["generated"];
    writer.Clear().AppendLine(fileContents[..generatedGroup.Index]);

    using (writer.Indented())
    {
        var errorMessages = PcreErrorMessage.ParseErrorFile(Path.Combine(pcre2SrcDir, "pcre2_error.c"))
                                            .ToDictionary(i => i.Value);

        var constantMapping = constants.Where(i => i.OptionFullName is not null)
                                       .ToDictionary(i => i.Name, i => i.OptionFullName);

        foreach (var constant in constants.Where(i => i.IsError))
        {
            var errorMessage = errorMessages[int.Parse(constant.Value)].ToXmlDocComment();

            errorMessage = Regex.Replace(
                errorMessage,
                @"\bPCRE2_[A-Z0-9_]+",
                m => constantMapping.TryGetValue(m.Value, out var optionFullName)
                    ? $"<see cref=\"{optionFullName}\"/>"
                    : $"<c>{m.Value}</c>"
            );

            errorMessage = errorMessage.Replace("INT_MAX", "<see cref=\"int.MaxValue\"/>");

            writer.AppendLine("/// <summary>");
            writer.AppendLine($"/// <c>{constant.Name}</c> - {errorMessage}");
            writer.AppendLine("/// </summary>");
            writer.AppendLine($"{constant.ToMemberName()} = PcreConstants.{constant.Name},");
            writer.AppendLine();
        }
    }

    writer.AppendLine().Append(fileContents[(generatedGroup.Index + generatedGroup.Length)..]);
    File.WriteAllText(errorCodeFilePath, writer.ToString());

    Console.WriteLine(" ✅ PcreErrorCode.cs updated");
}

internal readonly record struct PcreConstant(string Type, string Name, string Value, string? OptionFullName)
{
    private const string _errorPrefix = "PCRE2_ERROR_";

    public bool IsError => Name.StartsWith(_errorPrefix, StringComparison.Ordinal);

    public static IEnumerable<PcreConstant> Parse(string headerPath, string optionsPath, string extraOptionsPath)
    {
        var commentRe = new Regex(
            @"/\* .*? \*/",
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        var defineRe = new Regex(
            """
            ^ \s* \# \s* define \s+
            (?<name>PCRE2_\w+) \s+
            \(? \s*
            (?<value> -? (?:0x)? [0-9]+ )
            [uU]?
            \s* \)?
            \s* $
            """,
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace | RegexOptions.Multiline
        );

        var options = ParseOptions(
                optionsPath,
                extraOptionsPath
            ).Reverse()
             .DistinctBy(i => i.ConstantName)
             .ToDictionary(i => i.ConstantName, i => i.OptionFullName, StringComparer.Ordinal);

        foreach (var rawLine in File.ReadLines(headerPath))
        {
            if (rawLine.Contains("Obsolete", StringComparison.OrdinalIgnoreCase))
                continue;

            var line = commentRe.Replace(rawLine, string.Empty);
            var match = defineRe.Match(line);

            if (!match.Success)
                continue;

            var (name, value) = (match.Groups["name"].Value, match.Groups["value"].Value);

            if (name is "PCRE2_MAJOR" or "PCRE2_MINOR" or "PCRE2_LOCAL_WIDTH")
                continue;

            var type = name.StartsWith(_errorPrefix) ? "int" : "uint";

            yield return new PcreConstant(type, name, value, options.GetValueOrDefault(name));
        }
    }

    private static IEnumerable<(string ConstantName, string OptionFullName)> ParseOptions(string optionsPath, string extraOptionsPath)
    {
        var regex = new Regex(
            """
            ^ \s*(?<optionName>\w+)\s*=\s*PcreConstants\.(?<constantName>\w+)
            """,
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        foreach (var line in File.ReadLines(optionsPath))
        {
            var match = regex.Match(line);

            if (match.Success)
                yield return (match.Groups["constantName"].Value, $"PcreOptions.{match.Groups["optionName"].Value}");
        }

        foreach (var line in File.ReadLines(extraOptionsPath))
        {
            var match = regex.Match(line);

            if (match.Success)
                yield return (match.Groups["constantName"].Value, $"PcreExtraCompileOptions.{match.Groups["optionName"].Value}");
        }
    }

    public string ToMemberName()
    {
        var memberName = Name;

        if (IsError)
        {
            var constantNameWithoutPrefix = Name[_errorPrefix.Length..];
            memberName = constantNameWithoutPrefix;

            foreach (var cut in _errorCutPositions)
            {
                if (constantNameWithoutPrefix == cut.Replace("|", string.Empty))
                {
                    memberName = cut.Replace("|", "_");
                    break;
                }
            }
        }

        memberName = Regex.Replace(
            memberName.ToLowerInvariant(),
            @"(?:^|_)(?<char>\w)",
            m => m.Groups["char"].Value.ToUpperInvariant()
        );

        return memberName;
    }

    private static readonly string[] _errorCutPositions =
    [
        "QUERY_BAR|JX_NEST_TOO_DEEP",
        "E|CLASS_NEST_TOO_DEEP",
        "E|CLASS_INVALID_OPERATOR",
        "E|CLASS_UNEXPECTED_OPERATOR",
        "E|CLASS_EXPECTED_OPERAND",
        "E|CLASS_MIXED_OPERATORS",
        "E|CLASS_HINT_SQUARE_BRACKET",
        "PERL_E|CLASS_UNEXPECTED_EXPR",
        "PERL_E|CLASS_EMPTY_EXPR",
        "PERL_E|CLASS_MISSING_CLOSE",
        "PERL_E|CLASS_UNEXPECTED_CHAR",
        "NULL_ERROR|OFFSET",
        "NO|MATCH",
        "BAD|DATA",
        "MIXED|TABLES",
        "BAD|MAGIC",
        "BAD|MODE",
        "BAD|OFFSET",
        "BAD|OPTION",
        "BAD|REPLACEMENT",
        "BAD|UTF|OFFSET",
        "DFA_BAD|RESTART",
        "DFA_RECURSE",
        "DFA_U|COND",
        "DFA_U|FUNC",
        "DFA_U|ITEM",
        "DFA_WS|SIZE",
        "JIT_BAD|OPTION",
        "JIT_STACK|LIMIT",
        "MATCH|LIMIT",
        "NO|MEMORY",
        "NO|SUBSTRING",
        "NO|UNIQUE|SUBSTRING",
        "RECURSE|LOOP",
        "DEPTH|LIMIT",
        "BAD|OFFSET|LIMIT",
        "BAD|REP|ESCAPE",
        "REP|MISSING|BRACE",
        "BAD|SUBSTITUTION",
        "BAD|SUBS|PATTERN",
        "TOO|MANY|REPLACE",
        "BAD|SERIALIZED|DATA",
        "HEAP|LIMIT",
        "CONVERT|SYNTAX",
        "INTERNAL_DUP|MATCH",
        "DFA_U|INVALID_UTF",
        "INVALID|OFFSET",
        "JIT|UNSUPPORTED",
        "REPLACE|CASE",
        "TOO|LARGE|REPLACE",
        "DIFF|SUBS|PATTERN",
        "DIFF|SUBS|SUBJECT",
        "DIFF|SUBS|OFFSET",
        "DIFF|SUBS|OPTIONS",
        "BAD|BACKSLASH|K",
        "PARTIAL|SUBS",
    ];
}

internal readonly record struct PcreErrorMessage(int Value, string Message)
{
    public static IEnumerable<PcreErrorMessage> ParseErrorFile(string filePath)
    {
        // That's not the cleanest method, but the native library is not compiled at this point...

        using var enumerator = File.ReadAllLines(filePath).AsEnumerable().GetEnumerator();

        enumerator.AdvanceToMatch("compile_error_texts[] =");
        const int compileErrorBase = 100;
        var value = compileErrorBase;

        while (true)
        {
            var line = enumerator.AdvanceToNextLine().Trim();

            if (ShouldStop(line))
                break;

            if (ShouldSkipLine(line, value - compileErrorBase))
                continue;

            if (line == "#ifndef EBCDIC")
            {
                yield return new PcreErrorMessage(value++, GetMessage(enumerator.AdvanceToNextLine()));
                enumerator.AdvanceToMatch("#endif");
                continue;
            }

            yield return new PcreErrorMessage(value++, GetMessage(line));
        }

        enumerator.AdvanceToMatch("match_error_texts[] =");
        value = 0;

        while (true)
        {
            var line = enumerator.AdvanceToNextLine().Trim();

            if (ShouldStop(line))
                break;

            if (ShouldSkipLine(line, -value))
                continue;

            yield return new PcreErrorMessage(value--, GetMessage(line));
        }
    }

    private static bool ShouldStop(string line)
        => line == ";";

    private static bool ShouldSkipLine(string line, int expectedIndex)
    {
        if (line.StartsWith("/*", StringComparison.Ordinal) && line.EndsWith("*/", StringComparison.Ordinal))
        {
            if (int.TryParse(line[2..^2].Trim(), out var index) && index != expectedIndex)
                throw new InvalidOperationException($"Unexpected position: got {index}, expected: {expectedIndex}");

            return true;
        }

        return false;
    }

    private static string GetMessage(string line)
    {
        var match = Regex.Match(
            line,
            """
            ^ \s* " (?<message> .*? ) \\0 " \s*
            (?:
                /\* .* \*/ \s*
            )? $
            """,
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        if (!match.Success)
            throw new InvalidOperationException($"Unexpected line format: {line}");

        var message = match.Groups["message"].Value;

        message = message.Replace("\\\"", "\"")
                         .Replace("""\\""", """\""")
                         .Replace("""in UTF-" XSTRING(PCRE2_CODE_UNIT_WIDTH) " mode""", "in the used UTF mode")
                         .Replace(""" (maximum " XSTRING(MAX_NAME_SIZE) " code units)""", string.Empty)
                         .Replace(""" (maximum " XSTRING(MAX_NAME_COUNT) ")""", string.Empty);

        if (message.Contains("XSTRING"))
            throw new InvalidOperationException($"Unexpected XSTRING in message: {message}");

        return message;
    }

    public string ToXmlDocComment()
    {
        var errorMessage = WebUtility.HtmlEncode(Message)
                                     .Replace("&#39;", "'");

        errorMessage = Regex.Replace(
            errorMessage,
            """
            (?<=^|[ (])
            (?:
                [a-z0-9]+_[a-z0-9_]+ \(\)  # Function
                | \\   [^ ]+               # Escape
                | \(\? [^ ]+               # Group
                | \(\* [a-zA-Z_]+ \)       # Verb
                | { [^}]+ }                # Braces
                | (?! POSIX | ASCII | UTF | UCP | DFA | JIT | RFC ) [A-Z]{2,}
                | (?! - ) \W+
                | ^erroroffset
                | \$_
            )
            (?=[ :),]|$)
            """,
            "<c>$0</c>",
            RegexOptions.CultureInvariant | RegexOptions.IgnorePatternWhitespace
        );

        errorMessage = errorMessage.Replace("</c><c>", string.Empty)
                                   .Replace(",</c>", "</c>,");

        if (char.IsLower(errorMessage[0]))
            errorMessage = char.ToUpperInvariant(errorMessage[0]) + errorMessage.Substring(1);

        var lastChar = errorMessage[^1];
        if ((!char.IsPunctuation(lastChar) || lastChar is ')') && (!errorMessage.EndsWith("</c>") || errorMessage.EndsWith("()</c>")))
            errorMessage += ".";

        return errorMessage;
    }
}

file static class Extensions
{
    extension(IEnumerator<string> enumerator)
    {
        public string AdvanceToNextLine()
            => enumerator.MoveNext() ? enumerator.Current : throw new InvalidOperationException("Could not advance to the next line.");

        public void AdvanceToMatch(string content)
        {
            while (enumerator.MoveNext())
            {
                if (enumerator.Current.Contains(content))
                    return;
            }

            throw new InvalidOperationException($"Could not find '{content}'.");
        }
    }
}
